    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
              FechaNacimiento = new com.toedter.calendar.JDateChooser();

        String sCodigo = txtNorden.getText().trim();
    if (sCodigo.isEmpty()) {
        oFunc.SubSistemaMensajeError("Por favor ingrese un número de orden.");
        return;
    }

    String sql = ""
      + "SELECT "
      + "  d.cod_pa, "
      + "  d.nombres_pa || ' ' || d.apellidos_pa AS nombre, "
      + "  d.fecha_nacimiento_pa, "
      + "  n.razon_empresa, "
      + "  n.cargo_de, "
      + "  c.fecha_emo, "
      + "  c.tipo_emo, "
      + "  c.fecha_entrega "
      + "FROM datos_paciente d "
      + "INNER JOIN n_orden_ocupacional n ON d.cod_pa = n.cod_pa "
      + "INNER JOIN registro_conformidad_emo c ON c.n_orden = n.n_orden "
      + "WHERE n.n_orden = " + sCodigo;

    // Ejecutar la consulta
    if (!oConn.FnBoolQueryExecute(sql)) {
        oFunc.SubSistemaMensajeError("Error al ejecutar consulta de Conformidad EMO");
        return;
    }

    try {
        if (oConn.setResult.next()) {
            // Paciente
            txtApellidosNombres.setText(oConn.setResult.getString("nombre"));
            txtDNI.setText(          oConn.setResult.getString("cod_pa"));
            FechaNacimiento.setDate( oConn.setResult.getDate("fecha_nacimiento_pa"));

            // Empresa / Cargo
            txtEmpresa.setText(      oConn.setResult.getString("razon_empresa"));
            txtPuestoTrabajo.setText(oConn.setResult.getString("cargo_de"));

            // Tipo de EMO
            txtTipoEMO.setText(      oConn.setResult.getString("tipo_emo"));

            // Fecha EMO y Fecha de entrega
            FechaHoy .setDate(oConn.setResult.getDate("fecha_emo"));
            FechaHoy2.setDate(oConn.setResult.getDate("fecha_entrega"));

            // Edad calculada
            int edad = oFunc.calcularEdad(FechaNacimiento.getCalendar());
            txtEdad.setText(String.valueOf(edad));
        } else {
            oFunc.SubSistemaMensajeError("No se encontraron registros para la orden " + sCodigo);
        }
    } catch (SQLException ex) {
        oFunc.SubSistemaMensajeError("Error al leer resultados: " + ex.getMessage());
    } finally {
        try {
            if (oConn.setResult != null) oConn.setResult.close();
            if (oConn.sqlStmt   != null) oConn.sqlStmt.close();
        } catch (SQLException ex) {
            Logger.getLogger(this.getClass().getName())
                  .log(Level.SEVERE, null, ex);
        }
    }
    }//GEN-LAST:event_btnEditarActionPerformed

