   private boolean GrabarConformidad() throws SQLException {
    boolean bResult = false;

    // 1) Formatear fechas a YYYY-MM-DD
    SimpleDateFormat fmt = new SimpleDateFormat("yyyy-MM-dd");
    String fechaEMO    = fmt.format(FechaHoy.getDate());
    String fechaEntreg = fmt.format(FechaHoy2.getDate());

    // 2) Construir el INSERT
    StringBuilder sql = new StringBuilder();
    sql.append("INSERT INTO registro_conformidad_emo ")
       .append("(n_orden, fecha_emo, tipo_emo, apellidos_nombres, dni, puesto_trabajo, fecha_entrega, user_registro) VALUES (")
       // n_orden
       .append(txtNorden.getText().trim()).append(", ")
       // fecha_emo
       .append("'").append(fechaEMO).append("', ")
       // tipo_emo
       .append("'").append(txtTipoEMO.getText().trim()).append("', ")
       // apellidos_nombres
       .append("'").append(txtApellidosNombres.getText().trim()).append("', ")
       // dni
       .append("'").append(txtDNI.getText().trim()).append("', ")
       // puesto_trabajo
       .append("'").append(txtPuestoTrabajo.getText().trim()).append("', ")
       // fecha_entrega
       .append("'").append(fechaEntreg).append("', ")
       // user_registro
       .append("'").append(clsGlobales.sUser).append("')")
       ;

    System.out.println(sql.toString());

    // 3) Ejecutar la inserción
    if (oConn.FnBoolQueryExecuteUpdate(sql.toString())) {
        bResult = true;
        oFunc.SubSistemaMensajeInformacion("Registro de conformidad grabado correctamente");
    }

    // 4) Cerrar el statement
    try {
        oConn.sqlStmt.close();
    } catch (SQLException ex) {
        Logger.getLogger(this.getClass().getName())
              .log(Level.SEVERE, null, ex);
    }

    return bResult;
}



