  private void printer(Integer cod) throws IOException {
    if (cod == null || cod <= 0) {
        JOptionPane.showMessageDialog(this,
            "Código inválido para generar el reporte.",
            "Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Preparar parámetros
    Map<String, Object> parameters = new HashMap<>();
    parameters.put("Norden", cod);



    // Elegir plantilla según presencia de sello digitalizado
    String masterJasper;
        masterJasper = System.getProperty("user.dir")
                     + File.separator + "reportes"
                     + File.separator + "Constancia_lecturayentregade_resultados_boro.jasper";
    

    File reportFile = new File(masterJasper);
    if (!reportFile.exists()) {
        JOptionPane.showMessageDialog(this,
            "No se encontró el reporte en: " + masterJasper,
            "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Cargar y ejecutar Jasper
    try {
        JasperReport jasper  = (JasperReport) JRLoader.loadObject(reportFile);
        JasperPrint  print   = JasperFillManager.fillReport(
                                  jasper, parameters, clsConnection.oConnection);
        JasperPrintManager.printReport(print, true);
    } catch (JRException ex) {
        JOptionPane.showMessageDialog(this,
            "Error al generar el reporte: " + ex.getMessage(),
            "Error", JOptionPane.ERROR_MESSAGE);
    }
}

 
  
