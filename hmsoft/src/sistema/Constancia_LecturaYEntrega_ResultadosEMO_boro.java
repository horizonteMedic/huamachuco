    private void txtNordenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtNordenActionPerformed
        FechaNacimiento = new com.toedter.calendar.JDateChooser();

        String orden = txtNorden.getText().trim();
    if (orden.isEmpty()) {
        oFunc.SubSistemaMensajeError("Por favor ingrese un número de orden.");
        return;
    }
    if (OrdenExiste()) {
        oFunc.SubSistemaMensajeError("La orden ya existe en el sistema.");
        return;
    }
    String sql = ""
      + "SELECT "
      + "  d.nombres_pa || ' ' || d.apellidos_pa AS nombre, "
      + "  d.cod_pa, "
      + "  d.fecha_nacimiento_pa, "
      + "  n.razon_empresa, "
      + "  n.cargo_de, "
      + "  n.fecha_apertura_po, "    
      + "  n.nom_examen "
      + "FROM datos_paciente AS d "
      + "INNER JOIN n_orden_ocupacional AS n "
      + "  ON d.cod_pa = n.cod_pa "
      + "WHERE n.n_orden = " + orden;
    System.out.println(sql);

    if (!oConn.FnBoolQueryExecute(sql)) {
        oFunc.SubSistemaMensajeError("Error al ejecutar la consulta de paciente/orden.");
        return;
    }

    try {
        if (oConn.setResult.next()) {
            txtApellidosNombres.setText(oConn.setResult.getString("nombre"));
            txtDNI.setText( oConn.setResult.getString("cod_pa") );

            Date fnac = oConn.setResult.getDate("fecha_nacimiento_pa");
            FechaNacimiento.setDate(fnac);
            txtEdad.setText(
              String.valueOf(oFunc.calcularEdad(FechaNacimiento.getCalendar()))
            );

            txtEmpresa.setText(      oConn.setResult.getString("razon_empresa") );
            txtPuestoTrabajo.setText(oConn.setResult.getString("cargo_de")     );
            txtTipoEMO.setText(    oConn.setResult.getString("nom_examen")    );

            Date fechaEMO = oConn.setResult.getDate("fecha_apertura_po");
            FechaHoy.setDate(fechaEMO);

            txtNorden.setEditable(false);
            Fecha();  
        } else {
            oFunc.SubSistemaMensajeError(
              "No se encontró paciente u orden. Verifique el número ingresado."
            );
        }
    } catch (SQLException ex) {
        oFunc.SubSistemaMensajeInformacion("Error al leer datos: " + ex.getMessage());
    } finally {
        // 5) Cerrar siempre los recursos
        try {
            if (oConn.setResult != null) oConn.setResult.close();
            if (oConn.sqlStmt   != null) oConn.sqlStmt.close();
        } catch (SQLException ignore) {}
    }
    }//GEN-LAST:event_txtNordenActionPerformed
   public boolean OrdenExiste() {
    boolean bResultado = false;
    String orden = txtNorden.getText().trim();
    if (!orden.isEmpty()) {
      
        String sQuery = "SELECT n_orden FROM registro_conformidad_emo WHERE n_orden = " + orden;
        oConn.FnBoolQueryExecute(sQuery);
        try {
            if (oConn.setResult.next()) {
                bResultado = true;
            }
        } catch (SQLException ex) {
            oFunc.SubSistemaMensajeInformacion("Error al comprobar existencia de orden: " + ex.getMessage());
        } finally {
           
            try {
                if (oConn.setResult != null) oConn.setResult.close();
                if (oConn.sqlStmt   != null) oConn.sqlStmt.close();
            } catch (SQLException ignore) {}
        }
    }
    return bResultado;
}

    
