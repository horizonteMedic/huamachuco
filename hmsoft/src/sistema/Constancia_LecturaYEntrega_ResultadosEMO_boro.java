  private void ActualizarConformidad() {
    String sCodigo = txtNorden.getText().trim();
    if (sCodigo.isEmpty()) {
        oFunc.SubSistemaMensajeError("Por favor ingrese un número de orden.");
        return;
    }

    // Formatear la fecha EMO a YYYY-MM-DD
    String fechaFormateada = new java.text.SimpleDateFormat("yyyy-MM-dd")
        .format(FechaHoy.getDate());

    // Construir el UPDATE para tu tabla registro_conformidad_emo
    StringBuilder strSqlStmt = new StringBuilder();
    strSqlStmt.append("UPDATE registro_conformidad_emo ")
              .append("SET ")
              .append("  fecha_emo      = '").append(fechaFormateada).append("', ")
              .append("  user_registro  = '").append(clsGlobales.sUser).append("' ")
              .append("WHERE n_orden = ").append(sCodigo);

    System.out.println(strSqlStmt.toString());

    // Ejecutar la actualización
    if (oConn.FnBoolQueryExecuteUpdate(strSqlStmt.toString())) {
        oFunc.SubSistemaMensajeInformacion("Registro de conformidad actualizado con éxito");
        // Si necesitas refrescar la pantalla o limpiar campos, hazlo aquí:
        // limpiarFormulario();
    } else {
        oFunc.SubSistemaMensajeError("No se pudo actualizar el registro de conformidad");
    }

    // Cerrar el statement
    try {
        if (oConn.sqlStmt != null) oConn.sqlStmt.close();
    } catch (SQLException ex) {
        Logger.getLogger(this.getClass().getName())
              .log(Level.SEVERE, null, ex);
    }
}


